// Close Modal
function closeJobModal() {
  jobModal.style.display = "none";
  document.body.style.overflow = "auto";
  history.replaceState(null, "", window.location.pathname);
}

// Reset Filters
window.resetFilters = function() {
  if (searchInput) searchInput.value = "";
  if (clearSearchBtn) clearSearchBtn.style.display = "none";
  activeCategory = "all";
  activeState = "all";
  if (stateQuickFilter) stateQuickFilter.value = "all";

  document.querySelectorAll(".tab-btn").forEach(t => {
    t.classList.toggle("active", t.dataset.cat === "all");
  });

  applyAllFilters();
};

// Setup Event Listeners
function setupEventListeners() {
  // Real-time search
  if (searchInput) {
    searchInput.addEventListener("input", e => {
      clearSearchBtn.style.display = e.target.value ? "block" : "none";
      applyAllFilters();
    });
  }

  if (clearSearchBtn) {
    clearSearchBtn.addEventListener("click", () => {
      searchInput.value = "";
      clearSearchBtn.style.display = "none";
      applyAllFilters();
    });
  }

  // Category Tabs
  if (categoryTabs) {
    categoryTabs.addEventListener("click", e => {
      const btn = e.target.closest(".tab-btn");
      if (!btn) return;
      document.querySelectorAll(".tab-btn").forEach(t => t.classList.remove("active"));
      btn.classList.add("active");
      activeCategory = btn.dataset.cat;
      applyAllFilters();
    });
  }

  // View more buttons inside 3-column boxes
  document.querySelectorAll(".view-more-btn").forEach(btn => {
    btn.addEventListener("click", () => {
      const filter = btn.dataset.filter;
      activeCategory = filter;
      document.querySelectorAll(".tab-btn").forEach(t => {
        t.classList.toggle("active", t.dataset.cat === filter);
      });
      applyAllFilters();
      // Scroll to explorer
      document.querySelector(".explorer-section").scrollIntoView({ behavior: "smooth" });
    });
  });

  // State Filter
  if (stateQuickFilter) {
    stateQuickFilter.addEventListener("change", e => {
      activeState = e.target.value;
      applyAllFilters();
    });
  }

  // Modal Closers
  if (modalCloseBtn) modalCloseBtn.addEventListener("click", closeJobModal);
  if (modalFooterClose) modalFooterClose.addEventListener("click", closeJobModal);

  window.addEventListener("click", e => {
    if (e.target === jobModal) closeJobModal();
  });

  window.addEventListener("keydown", e => {
    if (e.key === "Escape" && jobModal.style.display === "flex") {
      closeJobModal();
    }
  });

  // Theme Toggle
  if (themeToggle) {
    themeToggle.addEventListener("click", toggleTheme);
  }
}

