  if (!job) return;

  // Header
  modalTitle.textContent = job.title;
  modalDepartment.textContent = `🏛️ विभाग: ${job.department} • राज्य: ${job.state}`;
  modalCategoryBadge.className = `badge ${getBadgeClass(job.category)}`;
  modalCategoryBadge.textContent = getCategoryName(job.category);

