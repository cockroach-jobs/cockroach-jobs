  // Direct Action Buttons
  const links = job.links || {};
  if (modalFullPageBtn) {
    modalFullPageBtn.href = `job.html?id=${job.id}`;
  }
  modalPrimaryBtn.textContent = links.primary_action || "⚡ सीधे आवेदन / परिणाम देखें";
